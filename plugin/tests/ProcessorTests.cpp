// Drives the real MelodeeProcessor with a simulated DAW transport and checks what comes out.

#include "PluginProcessor.h"

#include <iostream>
#include <map>

namespace
{
    int failures = 0;

    void check (bool ok, const juce::String& what)
    {
        std::cout << (ok ? "  ok    " : "  FAIL  ") << what << "\n";
        if (! ok)
            ++failures;
    }

    void pumpMessages()
    {
        juce::MessageManager::getInstance()->runDispatchLoopUntil (30);
    }

    struct FakePlayHead : public juce::AudioPlayHead
    {
        juce::Optional<PositionInfo> getPosition() const override
        {
            PositionInfo info;
            info.setIsPlaying (playing);
            info.setBpm (bpm);
            info.setPpqPosition (ppq);
            info.setTimeSignature (TimeSignature { 4, 4 });
            return info;
        }

        bool playing = true;
        double bpm = 120.0;
        double ppq = 0.0;
    };

    struct Captured
    {
        int channel;
        int note;
        double beat;
        bool on;
    };

    /** Runs the processor for `beats` beats from `startBeat` and returns every MIDI note event. */
    std::vector<Captured> run (MelodeeProcessor& p, FakePlayHead& ph, double startBeat, double beats, double sampleRate, int block, float* peak)
    {
        std::vector<Captured> out;
        juce::AudioBuffer<float> buffer (2, block);
        juce::MidiBuffer midi;

        const double beatsPerSample = ph.bpm / (60.0 * sampleRate);
        const int blocks = static_cast<int> (std::ceil (beats / (block * beatsPerSample)));

        for (int b = 0; b < blocks; ++b)
        {
            ph.ppq = startBeat + b * block * beatsPerSample;
            midi.clear();
            p.processBlock (buffer, midi);

            if (peak != nullptr)
                *peak = juce::jmax (*peak, buffer.getMagnitude (0, block));

            for (const auto m : midi)
            {
                const auto msg = m.getMessage();
                if (msg.isNoteOnOrOff())
                    out.push_back ({ msg.getChannel(), msg.getNoteNumber(), ph.ppq + m.samplePosition * beatsPerSample, msg.isNoteOn() });
            }
        }
        return out;
    }
} // namespace

int main()
{
    juce::ScopedJuceInitialiser_GUI juceInit;
    std::cout << "Melodee processor tests\n";

    MelodeeProcessor processor;
    pumpMessages();

    auto& session = processor.getSession();
    session.set (IDs::progression, "i VI III VII");
    session.generate (false);
    pumpMessages();

    check (session.variations().size() == 8, "eight variations are generated by default");
    check (session.progression().totalBeats == 16.0, "progression is four bars");

    const double sr = 48000.0;
    const int block = 480;
    processor.setPlayConfigDetails (0, 2, sr, block);
    processor.prepareToPlay (sr, block);

    FakePlayHead ph;
    processor.setPlayHead (&ph);

    // ---- One loop in sync with the host -----------------------------------------
    float peak = 0.0f;
    auto events = run (processor, ph, 0.0, 16.0, sr, block, &peak);

    std::map<int, int> onsPerChannel;
    for (const auto& e : events)
        if (e.on)
            ++onsPerChannel[e.channel];

    const auto* melody = session.selectedMelody();
    check (melody != nullptr, "a melody is selected");
    check (onsPerChannel[1] == static_cast<int> (melody->notes.size()),
           "melody notes on channel 1: " + juce::String (onsPerChannel[1]) + " of " + juce::String (melody->notes.size()));
    check (onsPerChannel[2] == static_cast<int> (session.chordNotes().size()),
           "chord notes on channel 2: " + juce::String (onsPerChannel[2]) + " of " + juce::String (session.chordNotes().size()));
    check (onsPerChannel[3] == static_cast<int> (session.bassNotes().size()),
           "bass notes on channel 3: " + juce::String (onsPerChannel[3]) + " of " + juce::String (session.bassNotes().size()));
    check (peak > 0.001f, "the built-in synth makes sound (peak " + juce::String (peak, 3) + ")");

    // Timing: the first melody note lands where the generator put it.
    {
        double firstOn = -1.0;
        for (const auto& e : events)
            if (e.on && e.channel == 1)
            {
                firstOn = e.beat;
                break;
            }
        check (std::abs (firstOn - melody->notes.front().start) < 0.01,
               "first melody note at beat " + juce::String (firstOn, 3) + " (expected " + juce::String (melody->notes.front().start, 3) + ")");
    }

    // ---- The loop wraps: the second pass repeats the first --------------------------
    {
        auto second = run (processor, ph, 16.0, 16.0, sr, block, nullptr);
        int ons = 0;
        for (const auto& e : second)
            ons += (e.on && e.channel == 1) ? 1 : 0;
        check (ons == static_cast<int> (melody->notes.size()), "second loop plays the melody again");
    }

    // ---- Stop: everything is released -------------------------------------------------
    {
        auto lead = run (processor, ph, 40.0, 1.5, sr, block, nullptr);
        std::map<std::pair<int, int>, int> sounding;
        for (const auto& e : lead)
            sounding[{ e.channel, e.note }] = e.on ? 1 : 0;

        ph.playing = false;
        auto stop = run (processor, ph, 41.5, 0.1, sr, block, nullptr);
        for (const auto& e : stop)
            if (! e.on)
                sounding[{ e.channel, e.note }] = 0;

        bool released = true, silentAfter = true;
        for (const auto& [key, on] : sounding)
            released = released && on == 0;
        for (const auto& e : stop)
            silentAfter = silentAfter && ! e.on;
        check (released && silentAfter, "stopping the host releases every sounding note");
        ph.playing = true;
    }

    // ---- A host jump (e.g. a loop region) releases what was sounding ----------------------
    {
        auto a = run (processor, ph, 3.0, 1.0, sr, block, nullptr);
        std::map<std::pair<int, int>, int> sounding;
        for (const auto& e : a)
            sounding[{ e.channel, e.note }] = e.on ? 1 : 0;

        auto b = run (processor, ph, 10.0, 0.02, sr, block, nullptr);
        for (const auto& e : b)
            if (! e.on)
                sounding[{ e.channel, e.note }] = 0;

        bool released = true;
        for (const auto& [key, on] : sounding)
            released = released && on == 0;
        check (released, "jumping to another position releases held notes");
    }

    // ---- Preview clock without the host ---------------------------------------------------
    {
        ph.playing = false;
        processor.setPreviewing (true);
        auto preview = run (processor, ph, 0.0, 4.0, sr, block, nullptr);
        int ons = 0;
        for (const auto& e : preview)
            ons += e.on ? 1 : 0;
        check (ons > 0, "preview plays when the DAW is stopped (" + juce::String (ons) + " notes in one bar)");
        processor.setPreviewing (false);
        run (processor, ph, 0.0, 0.1, sr, block, nullptr);
        ph.playing = true;
    }

    // ---- Parts can be muted -----------------------------------------------------------------
    {
        session.set (IDs::playChords, false);
        session.set (IDs::playBass, false);
        pumpMessages();
        auto onlyMelody = run (processor, ph, 0.0, 16.0, sr, block, nullptr);
        bool ok = true;
        for (const auto& e : onlyMelody)
            ok = ok && e.channel == 1;
        check (ok, "muting chords and bass leaves only the melody");
        session.set (IDs::playChords, true);
        session.set (IDs::playBass, true);
        pumpMessages();
    }

    // ---- Output mode: everything on channel 1 ------------------------------------------------
    {
        session.set (IDs::outputMode, 1);
        pumpMessages();
        auto all = run (processor, ph, 0.0, 8.0, sr, block, nullptr);
        bool ok = ! all.empty();
        for (const auto& e : all)
            ok = ok && e.channel == 1;
        check (ok, "output mode 'all on channel 1'");
        session.set (IDs::outputMode, 0);
        pumpMessages();
    }

    // ---- Keyboard: scale lock and chord trigger ---------------------------------------------------
    {
        ph.playing = false;
        session.set (IDs::keyboardMode, 1);
        pumpMessages();

        juce::AudioBuffer<float> buffer (2, block);
        juce::MidiBuffer midi;
        midi.addEvent (juce::MidiMessage::noteOn (1, 61, static_cast<juce::uint8> (100)), 0); // C# is not in A minor
        processor.processBlock (buffer, midi);
        int played = -1;
        for (const auto m : midi)
            if (m.getMessage().isNoteOn())
                played = m.getMessage().getNoteNumber();
        check (played == 60 || played == 62, "scale lock moves C# into A minor (played " + juce::String (played) + ")");

        midi.clear();
        midi.addEvent (juce::MidiMessage::noteOff (1, 61), 0);
        processor.processBlock (buffer, midi);

        session.set (IDs::keyboardMode, 2);
        pumpMessages();
        midi.clear();
        midi.addEvent (juce::MidiMessage::noteOn (1, 48, static_cast<juce::uint8> (100)), 0); // C = chord 1
        processor.processBlock (buffer, midi);
        std::vector<int> chordNotes;
        for (const auto m : midi)
            if (m.getMessage().isNoteOn())
                chordNotes.push_back (m.getMessage().getNoteNumber() % 12);
        const auto voicing = session.chordVoicings().front();
        bool sameChord = chordNotes.size() == voicing.size();
        for (size_t i = 0; sameChord && i < voicing.size(); ++i)
            sameChord = chordNotes[i] == voicing[i] % 12;
        check (sameChord, "chord trigger: a white key plays the first chord (" + juce::String (static_cast<int> (chordNotes.size())) + " notes)");

        session.set (IDs::keyboardMode, 0);
        pumpMessages();
        ph.playing = true;
    }

    // ---- Transform, then save and restore the whole session ------------------------------------------
    {
        session.applyTransform (static_cast<int> (melodee::MelodyTransform::Inversion));
        pumpMessages();
        check (session.variations().size() == 9, "a 'Vary' adds a ninth variation");

        juce::MemoryBlock state;
        processor.getStateInformation (state);

        MelodeeProcessor restored;
        restored.setStateInformation (state.getData(), static_cast<int> (state.getSize()));
        pumpMessages();

        auto& rs = restored.getSession();
        check (rs.variations().size() == session.variations().size(), "variations are restored with the project");
        check (rs.get (IDs::progression).toString() == "i VI III VII", "progression text is restored");
        check (rs.selectedIndex() == session.selectedIndex(), "selected variation is restored");

        bool sameNotes = rs.selectedMelody() != nullptr && rs.selectedMelody()->notes.size() == session.selectedMelody()->notes.size();
        for (size_t i = 0; sameNotes && i < session.selectedMelody()->notes.size(); ++i)
            sameNotes = rs.selectedMelody()->notes[i].pitch == session.selectedMelody()->notes[i].pitch
                     && std::abs (rs.selectedMelody()->notes[i].start - session.selectedMelody()->notes[i].start) < 1e-3;
        check (sameNotes, "melody notes survive save/restore");
    }

    // ---- Changing key transposes the melodies -------------------------------------------------
    {
        const auto before = session.selectedMelody()->notes.front().pitch;
        session.set (IDs::key, 11); // A -> B
        pumpMessages();
        const auto after = session.selectedMelody()->notes.front().pitch;
        check (melodee::mod12 (after - before) == 2, "key change from A to B transposes the melody up a whole step");
        check (session.baseProgression().chords.front().chord.name() == "Bm", "roman numerals follow the new key");
    }

    // ---- MIDI export ------------------------------------------------------------------------------
    {
        const auto data = session.createMidi (Session::AllParts, 120.0);
        std::vector<std::uint8_t> bytes (static_cast<const std::uint8_t*> (data.getData()),
                                         static_cast<const std::uint8_t*> (data.getData()) + data.getSize());
        const auto tracks = melodee::readMidiFile (bytes);
        check (tracks.size() == 4, "exported MIDI has tempo + melody + chords + bass tracks");
        check (session.suggestedFileName (Session::MelodyPart).endsWith (".mid"), "file name: " + session.suggestedFileName (Session::MelodyPart));
    }

    // ---- The editor can be created and laid out headlessly ------------------------------------------
    {
        std::unique_ptr<juce::AudioProcessorEditor> editor (processor.createEditor());
        editor->setSize (1300, 820);
        check (editor->getWidth() == 1300, "editor opens and resizes");
        editor.reset();
    }

    processor.releaseResources();
    std::cout << "\n" << (failures == 0 ? "All processor tests passed" : juce::String (failures) + " FAILED") << "\n";
    return failures == 0 ? 0 : 1;
}
